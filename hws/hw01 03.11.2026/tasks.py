    thresholds = [1e-9, 1e-6, 1e-3]
    steps_reached = {th: None for th in thresholds} # Создаем словарь, чтобы запомнить, на каком именно шаге цикла погрешность впервые превысила заданный лимит
    
    for i in range(1, 10001):
        x *= 1.0001

        # Считаем идеальное значение для данного шага
        ideal_current = math.exp(i * math.log(1.0001))
        
        # Считаем текущую относительную погрешность
        rel_err = relative_error(x, ideal_current)
        
        # Если номер шага есть в нашем списке для таблицы, то сохраняем
        if i in steps_to_print:
            table_data.append((i, x, rel_err))
            
        # Проверяем пороги
        for th in thresholds:
            if steps_reached[th] is None and rel_err > th:
                steps_reached[th] = i

    print(f"\tТочное значение: {exact_val:.10e}\n")
    
    # Вывод в виде таблицы. В задании написано сделать график, но на паре вы говорили, чтобы мы пока не делали графики, а делали таблицы
    print(f"\t{'Шаг (i)':<10} | {'Значение x':<20} | {'δx':<25}")
    print("\t" + "-" * 60)
