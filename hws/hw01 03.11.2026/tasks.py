import math
import random
from decimal import Decimal, getcontext

def absolute_error(approx, exact): 
    return abs(approx - exact)

def relative_error(approx, exact): 
    if exact == 0: 
        return float('inf') # защита
    return abs(approx - exact) / abs(exact)

