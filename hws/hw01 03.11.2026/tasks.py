def task11():
    print("\n\t---- Задание 11 ----\n")
    
    a = 1 + 10**-15
    b = 1.0
    expected_diff = 10**-15
    actual_diff = a - b
    
    print(f"\tОжидаемый ответ (1 + 10^-15 - 1): {expected_diff:.2e}")
    print(f"\tРеальный результат: {actual_diff:.2e}")
    
    # Относительная погрешность результата
    # Считаем разницу между фактическим и ожидаемым, делим на ожидаемое
    rel_error = relative_error(actual_diff, expected_diff) * 100
    print(f"\tОтносительная погрешность: {rel_error} %\n")
    

    # Квадратное уравнение
    a = 1.0
    b = 1e8
    c = 1.0
    
    # через дискриминант
    # x1, 2 = (-b -+ sqrt(D)) / (2a)  -> большой корень по модулю
    D = b**2 - 4*a*c
    sqrt_D = math.sqrt(D)
    
    x1_standard = (-b - sqrt_D) / (2 * a)
    x2_standard = (-b + sqrt_D) / (2 * a)
    
    # Без вычитания близких чисел
    # Используем теорему Виета: x1 * x2 = c / a
    # Значит, x2 = c / (a * x1)
    # Сначала находим большой корень (там нет потери точности, т.к. складываем большие числа)
    x1_improved = (-b - sqrt_D) / (2 * a) 
    # Маленький корень находим через деление
    x2_improved = c / (a * x1_improved)

    print(f"\tСтандартная формула:")
    print(f"\t\tx1 = {x1_standard}")
    print(f"\t\tx2 = {x2_standard}\n")
    
    print(f"\tЧерез Виета:")
    print(f"\t\tx1 = {x1_improved}")
    print(f"\t\tx2 = {x2_improved}\n")

    print("\t--- Вывод по задаче 11 ---")
    print("\tPython не смог сохранить 10^-15 при вычитании, так как это число слишком мало по сравнению с 1.0, поэтому результат оказался с огромной относительной ошибкой.")
    print("\tСтандартная формула для x2 вычитает почти равные числа, что приводит к потере точности.")
    print("\tИспользование теоремы Виета позволяет избежать вычитания близких чисел и дает более точный корень.")

