def task4():
    print("\n\t---- Задание 4 ----\n")
    
    x_approx = 47.3
    max_rel_error = 0.1 / 100 # Переводим проценты в доли
    
    # δx = |x - x*| / |x*|
    # Следовательно |x - x*| <= δx * |x*|
    # Относительная погрешность 0.1% означает, что истинное значение (x*) 
    # может отклоняться от x на 0.1%. 
    # Так как погрешность считается относительно x*, 
    # границы считаются  x <= δ ⋅ x∗ +- x∗
    # следовательно x <= x∗ (δ +- 1)
    # Верхняя граница (b) = x / (1 - δ)
    # Нижняя граница (a) = x / (1 + δ)
    
    lower_bound = x_approx / (1 + max_rel_error)
    upper_bound = x_approx / (1 - max_rel_error)
    
    print(f"\tДиапазон, в котором лежит x*: [{lower_bound}, {upper_bound}]\n")

    print("\t--- Вывод по задаче 4 ---")
    print(f"\tТочное значение x* лежит в интервале [{lower_bound}, {upper_bound}].")
    print("\tТак как о δx не превышает 0.1%, диапазон отклонения составляет примерно ±0.047 от приближенного значения 47.3.")
    print("\tЭто означает, что измерение достаточно точное, и истинное значение гарантированно находится в этих узких пределах.")

